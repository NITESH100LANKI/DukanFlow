import React, { useState, useEffect, useCallback, useMemo } from 'react';
import { useOutletContext, Link } from 'react-router-dom';
import {
  getExportableOrders,
  getExportProfiles,
  createExportBatch,
  getExportBatches,
  downloadExportBatch,
  ExportableOrderItem,
  ExportProfile,
  ExportBatchListItem,
} from '../../api/exports';
import { Language } from '../../components/LanguageToggle';

export const DeskExportOrdersPage: React.FC = () => {
  const { language } = useOutletContext<{ language: Language }>();

  // State
  const [activeTab, setActiveTab] = useState<'orders' | 'history'>('orders');
  const [orders, setOrders] = useState<ExportableOrderItem[]>([]);
  const [profiles, setProfiles] = useState<ExportProfile[]>([]);
  const [selectedProfile, setSelectedProfile] = useState<string>('generic');
  const [batches, setBatches] = useState<ExportBatchListItem[]>([]);

  // Selection
  const [selectedIds, setSelectedIds] = useState<string[]>([]);

  // Filtering & Pagination
  const [search, setSearch] = useState<string>('');
  const [dateFrom, setDateFrom] = useState<string>('');
  const [dateTo, setDateTo] = useState<string>('');
  const [page, setPage] = useState<number>(1);
  const [totalPages, setTotalPages] = useState<number>(1);
  const [totalOrders, setTotalOrders] = useState<number>(0);

  // Status & Feedback
  const [loading, setLoading] = useState<boolean>(true);
  const [exporting, setExporting] = useState<boolean>(false);
  const [downloadingId, setDownloadingId] = useState<string | null>(null);
  const [error, setError] = useState<string | null>(null);
  const [successMessage, setSuccessMessage] = useState<string | null>(null);

  // Translations
  const t = {
    en: {
      title: 'Accounting Export & Tally Integration',
      subtitle: 'Export approved DukaanFlow wholesale orders into standardized accounting CSV formats',
      tallyNoticeHeader: 'Notice: Client Tally Import Format Pending Confirmation',
      tallyNoticeBody:
        'The export uses a generic, accounting-friendly CSV format (immutable order snapshots, separated free-goods benefit values, and zero invented GST). Once the client provides and validates their official Tally Prime voucher specification, a verified Tally import adapter will be enabled.',
      tabOrders: 'Approved Orders',
      tabHistory: 'Export History',
      searchPlaceholder: 'Search order number, retailer name, or ledger...',
      dateFromLabel: 'From Date',
      dateToLabel: 'To Date',
      filterButton: 'Filter',
      resetButton: 'Reset',
      selectAll: 'Select All on Page',
      selectedSummary: 'Selected Orders',
      casesSummary: 'Fulfilment Cases',
      netPayableSummary: 'Net Payable Total',
      profileLabel: 'Export Profile',
      exportCta: 'Generate & Download CSV',
      exporting: 'Generating CSV...',
      colOrderNumber: 'Order #',
      colDate: 'Order Date',
      colRetailer: 'Retailer & Party Ledger',
      colCases: 'Paid / Free / Fulfilment',
      colGross: 'Gross Amount',
      colNet: 'Net Payable',
      colExportStatus: 'Export Status',
      badgeNotExported: 'Not Exported',
      badgeExported: 'Exported',
      emptyOrders: 'No approved orders found matching your filters.',
      emptyHistory: 'No export batches generated yet.',
      colBatchNumber: 'Batch #',
      colGeneratedAt: 'Generated At',
      colOperator: 'Generated By',
      colOrdersCount: 'Orders',
      colRecordsCount: 'Items',
      colTotalNet: 'Total Net',
      colAction: 'Download',
      downloadBtn: 'Download CSV',
      downloading: 'Downloading...',
      backToQueue: '← Back to Order Queue',
    },
    hi: {
      title: 'अकाउंटिंग एक्सपोर्ट और टैली इंटीग्रेशन',
      subtitle: 'स्वीकृत थोक ऑर्डर्स को मानकीकृत अकाउंटिंग CSV में एक्सपोर्ट करें',
      tallyNoticeHeader: 'सूचना: टैली इम्पोर्ट फॉर्मेट क्लाइंट पुष्टि हेतु लंबित है',
      tallyNoticeBody:
        'यह एक्सपोर्ट जेनेरिक अकाउंटिंग CSV का उपयोग करता है (अपरिवर्तनीय ऑर्डर स्नैपशॉट, अलग से लाभ मूल्य, और शून्य कल्पित GST)। क्लाइंट द्वारा टैली वाउचर विनिर्देश प्रदान करने पर सत्यापित टैली एडाप्टर सक्रिय किया जाएगा।',
      tabOrders: 'स्वीकृत ऑर्डर्स',
      tabHistory: 'एक्सपोर्ट इतिहास',
      searchPlaceholder: 'ऑर्डर नंबर, किराना नाम या लेजर खोजें...',
      dateFromLabel: 'प्रारंभ तिथि',
      dateToLabel: 'अंतिम तिथि',
      filterButton: 'फ़िल्टर',
      resetButton: 'रीसेट',
      selectAll: 'इस पृष्ठ के सभी चुनें',
      selectedSummary: 'चयनित ऑर्डर्स',
      casesSummary: 'कुल डिलीवरी केस',
      netPayableSummary: 'कुल देय राशि',
      profileLabel: 'एक्सपोर्ट प्रोफाइल',
      exportCta: 'CSV जनरेट और डाउनलोड करें',
      exporting: 'CSV जनरेट हो रहा है...',
      colOrderNumber: 'ऑर्डर #',
      colDate: 'ऑर्डर दिनांक',
      colRetailer: 'किराना एवं पार्टी लेजर',
      colCases: 'भुगतान / मुफ़्त / कुल केस',
      colGross: 'सकल राशि',
      colNet: 'शुद्ध देय राशि',
      colExportStatus: 'एक्सपोर्ट स्थिति',
      badgeNotExported: 'एक्सपोर्ट नहीं हुआ',
      badgeExported: 'एक्सपोर्टेड',
      emptyOrders: 'फ़िल्टर के अनुसार कोई स्वीकृत ऑर्डर नहीं मिला।',
      emptyHistory: 'अभी तक कोई एक्सपोर्ट बैच नहीं बनाया गया है।',
      colBatchNumber: 'बैच #',
      colGeneratedAt: 'जनरेट समय',
      colOperator: 'ऑपरेटर',
      colOrdersCount: 'ऑर्डर्स',
      colRecordsCount: 'आइटम',
      colTotalNet: 'कुल शुद्ध राशि',
      colAction: 'डाउनलोड',
      downloadBtn: 'CSV डाउनलोड',
      downloading: 'डाउनलोडिंग...',
      backToQueue: '← ऑर्डर कतार पर वापस जाएं',
    },
  }[language];

  // Fetch profiles once
  useEffect(() => {
    getExportProfiles()
      .then((data) => {
        setProfiles(data);
        if (data.length > 0) {
          setSelectedProfile(data[0].key);
        }
      })
      .catch((err) => {
        console.error('Failed to load export profiles', err);
      });
  }, []);

  // Fetch exportable orders
  const fetchOrders = useCallback(async () => {
    setLoading(true);
    setError(null);
    try {
      const res = await getExportableOrders({
        page,
        page_size: 20,
        search: search || undefined,
        date_from: dateFrom || undefined,
        date_to: dateTo || undefined,
      });
      setOrders(res.items);
      setTotalPages(res.total_pages);
      setTotalOrders(res.total);
    } catch (err: any) {
      setError(err.response?.data?.detail || 'Failed to load exportable orders');
    } finally {
      setLoading(false);
    }
  }, [page, search, dateFrom, dateTo]);

  // Fetch export history
  const fetchHistory = useCallback(async () => {
    try {
      const res = await getExportBatches({ page: 1, page_size: 50 });
      setBatches(res.items);
    } catch (err) {
      console.error('Failed to load export history', err);
    }
  }, []);

  useEffect(() => {
    if (activeTab === 'orders') {
      fetchOrders();
    } else {
      fetchHistory();
    }
  }, [activeTab, fetchOrders, fetchHistory]);

  // Handle single selection toggle
  const toggleSelectOrder = (id: string) => {
    setSelectedIds((prev) =>
      prev.includes(id) ? prev.filter((item) => item !== id) : [...prev, id]
    );
  };

  // Handle Select All on Page
  const isAllPageSelected = useMemo(() => {
    if (orders.length === 0) return false;
    return orders.every((o) => selectedIds.includes(o.id));
  }, [orders, selectedIds]);

  const toggleSelectAllPage = () => {
    if (isAllPageSelected) {
      const pageIds = new Set(orders.map((o) => o.id));
      setSelectedIds((prev) => prev.filter((id) => !pageIds.has(id)));
    } else {
      const combined = new Set([...selectedIds, ...orders.map((o) => o.id)]);
      setSelectedIds(Array.from(combined));
    }
  };

  // Calculate selected summary metrics
  const selectedMetrics = useMemo(() => {
    const selectedSet = new Set(selectedIds);
    let totalFulfilmentCases = 0;
    let totalNet = 0;

    for (const o of orders) {
      if (selectedSet.has(o.id)) {
        totalFulfilmentCases += o.total_fulfilment_cases;
        totalNet += Number(o.net_total);
      }
    }

    return {
      count: selectedIds.length,
      cases: totalFulfilmentCases,
      net: totalNet,
    };
  }, [selectedIds, orders]);

  // Trigger Export
  const handleExport = async () => {
    if (selectedIds.length === 0) return;
    setExporting(true);
    setError(null);
    setSuccessMessage(null);

    try {
      const batch = await createExportBatch({
        order_ids: selectedIds,
        profile: selectedProfile,
      });

      setSuccessMessage(
        language === 'hi'
          ? `सफलतापूर्वक बैच ${batch.batch_number} जनरेट हुआ (${batch.order_count} ऑर्डर्स, ${batch.record_count} रिकॉर्ड्स)`
          : `Successfully generated batch ${batch.batch_number} (${batch.order_count} orders, ${batch.record_count} items)`
      );

      // Automatically trigger download
      await downloadExportBatch(batch.id, batch.csv_filename);

      // Refresh orders and clear selection
      setSelectedIds([]);
      fetchOrders();
    } catch (err: any) {
      setError(err.response?.data?.detail || 'Failed to generate export CSV');
    } finally {
      setExporting(false);
    }
  };

  // Handle manual download of existing batch
  const handleDownloadExisting = async (batch: ExportBatchListItem) => {
    setDownloadingId(batch.id);
    try {
      await downloadExportBatch(batch.id, batch.csv_filename);
    } catch (err) {
      console.error('Download failed', err);
    } finally {
      setDownloadingId(null);
    }
  };

  return (
    <div className="space-y-6">
      {/* Header and Back Link */}
      <div className="flex flex-col sm:flex-row justify-between items-start sm:items-center gap-4">
        <div>
          <Link
            to="/desk/orders"
            className="text-xs font-bold text-primary-600 hover:text-primary-700 transition-colors inline-block mb-1"
          >
            {t.backToQueue}
          </Link>
          <h1 className="text-2xl font-black text-gray-900 tracking-tight">{t.title}</h1>
          <p className="text-sm text-gray-600">{t.subtitle}</p>
        </div>

        {/* Tab Switcher */}
        <div className="flex bg-gray-100 p-1 rounded-xl border border-gray-200">
          <button
            onClick={() => setActiveTab('orders')}
            className={`px-4 py-1.5 rounded-lg text-xs font-bold transition-all ${
              activeTab === 'orders'
                ? 'bg-white text-primary-700 shadow-sm'
                : 'text-gray-600 hover:text-gray-900'
            }`}
          >
            {t.tabOrders} ({totalOrders})
          </button>
          <button
            onClick={() => setActiveTab('history')}
            className={`px-4 py-1.5 rounded-lg text-xs font-bold transition-all ${
              activeTab === 'history'
                ? 'bg-white text-primary-700 shadow-sm'
                : 'text-gray-600 hover:text-gray-900'
            }`}
          >
            {t.tabHistory}
          </button>
        </div>
      </div>

      {/* Mandatory Tally Confirmation Notice Banner */}
      <div className="bg-amber-50 border-l-4 border-amber-500 p-4 rounded-r-xl shadow-sm">
        <div className="flex items-start">
          <div className="flex-shrink-0 text-amber-600 text-lg">⚠️</div>
          <div className="ml-3">
            <h3 className="text-sm font-bold text-amber-800">{t.tallyNoticeHeader}</h3>
            <p className="text-xs text-amber-700 mt-0.5 leading-relaxed">{t.tallyNoticeBody}</p>
          </div>
        </div>
      </div>

      {/* Feedback Messages */}
      {error && (
        <div className="bg-red-50 border border-red-200 text-red-700 px-4 py-3 rounded-xl text-xs font-medium">
          {error}
        </div>
      )}
      {successMessage && (
        <div className="bg-green-50 border border-green-200 text-green-800 px-4 py-3 rounded-xl text-xs font-medium flex justify-between items-center">
          <span>{successMessage}</span>
          <button
            onClick={() => setSuccessMessage(null)}
            className="text-green-600 hover:text-green-800 font-bold ml-2"
          >
            ✕
          </button>
        </div>
      )}

      {/* Tab 1: Approved Orders Export */}
      {activeTab === 'orders' && (
        <div className="space-y-4">
          {/* Filters Bar */}
          <div className="bg-white p-4 rounded-2xl border border-gray-200 shadow-sm flex flex-col md:flex-row gap-3 items-stretch md:items-end">
            <div className="flex-1">
              <label className="block text-[11px] font-bold uppercase tracking-wider text-gray-500 mb-1">
                Search
              </label>
              <input
                type="text"
                value={search}
                onChange={(e) => setSearch(e.target.value)}
                placeholder={t.searchPlaceholder}
                className="w-full text-xs px-3 py-2 border border-gray-300 rounded-lg focus:ring-2 focus:ring-primary-500 focus:outline-none"
              />
            </div>
            <div className="w-full md:w-36">
              <label className="block text-[11px] font-bold uppercase tracking-wider text-gray-500 mb-1">
                {t.dateFromLabel}
              </label>
              <input
                type="date"
                value={dateFrom}
                onChange={(e) => setDateFrom(e.target.value)}
                className="w-full text-xs px-2.5 py-2 border border-gray-300 rounded-lg focus:ring-2 focus:ring-primary-500 focus:outline-none"
              />
            </div>
            <div className="w-full md:w-36">
              <label className="block text-[11px] font-bold uppercase tracking-wider text-gray-500 mb-1">
                {t.dateToLabel}
              </label>
              <input
                type="date"
                value={dateTo}
                onChange={(e) => setDateTo(e.target.value)}
                className="w-full text-xs px-2.5 py-2 border border-gray-300 rounded-lg focus:ring-2 focus:ring-primary-500 focus:outline-none"
              />
            </div>
            <div className="flex gap-2">
              <button
                onClick={() => {
                  setPage(1);
                  fetchOrders();
                }}
                className="px-4 py-2 bg-gray-900 hover:bg-gray-800 text-white text-xs font-bold rounded-lg transition-colors"
              >
                {t.filterButton}
              </button>
              {(search || dateFrom || dateTo) && (
                <button
                  onClick={() => {
                    setSearch('');
                    setDateFrom('');
                    setDateTo('');
                    setPage(1);
                  }}
                  className="px-3 py-2 bg-gray-100 hover:bg-gray-200 text-gray-700 text-xs font-bold rounded-lg transition-colors"
                >
                  {t.resetButton}
                </button>
              )}
            </div>
          </div>

          {/* Action Summary & Profile Selector */}
          <div className="bg-gradient-to-r from-primary-900 to-indigo-900 text-white p-4 rounded-2xl shadow-md flex flex-col md:flex-row justify-between items-stretch md:items-center gap-4">
            <div className="flex flex-wrap items-center gap-6">
              <div className="flex items-center gap-2">
                <input
                  type="checkbox"
                  id="select-all-checkbox"
                  checked={isAllPageSelected}
                  onChange={toggleSelectAllPage}
                  className="h-4 w-4 rounded border-gray-300 text-primary-600 focus:ring-primary-500 cursor-pointer"
                />
                <label
                  htmlFor="select-all-checkbox"
                  className="text-xs font-bold cursor-pointer select-none"
                >
                  {t.selectAll}
                </label>
              </div>

              <div className="h-4 w-px bg-primary-700 hidden sm:block" />

              <div>
                <span className="text-[11px] text-primary-200 block uppercase font-bold tracking-wider">
                  {t.selectedSummary}
                </span>
                <span data-testid="selected-count" className="text-lg font-black">{selectedMetrics.count}</span>
              </div>

              <div>
                <span className="text-[11px] text-primary-200 block uppercase font-bold tracking-wider">
                  {t.casesSummary}
                </span>
                <span data-testid="selected-cases" className="text-lg font-black">{selectedMetrics.cases}</span>
              </div>

              <div>
                <span className="text-[11px] text-primary-200 block uppercase font-bold tracking-wider">
                  {t.netPayableSummary}
                </span>
                <span data-testid="selected-net" className="text-lg font-black text-amber-300">
                  ₹{selectedMetrics.net.toLocaleString('en-IN', { minimumFractionDigits: 2 })}
                </span>
              </div>
            </div>

            <div className="flex flex-col sm:flex-row items-stretch sm:items-center gap-3">
              <div className="flex flex-col">
                <span className="text-[10px] text-primary-200 uppercase font-bold mb-0.5">
                  {t.profileLabel}
                </span>
                <select
                  value={selectedProfile}
                  onChange={(e) => setSelectedProfile(e.target.value)}
                  className="bg-primary-800 text-white text-xs px-3 py-1.5 rounded-lg border border-primary-700 focus:outline-none focus:ring-2 focus:ring-amber-400 font-medium"
                >
                  {profiles.map((p) => (
                    <option key={p.key} value={p.key} className="bg-gray-900 text-white">
                      {p.display_name}
                    </option>
                  ))}
                </select>
              </div>

              <button
                onClick={handleExport}
                disabled={selectedIds.length === 0 || exporting}
                className="mt-auto sm:mt-0 px-5 py-2.5 bg-amber-400 hover:bg-amber-300 disabled:bg-gray-700 disabled:text-gray-400 disabled:cursor-not-allowed text-gray-950 font-black text-xs rounded-xl shadow-lg transition-all transform active:scale-95 inline-flex items-center justify-center gap-1.5"
              >
                <span>📦</span>
                <span>{exporting ? t.exporting : t.exportCta}</span>
              </button>
            </div>
          </div>

          {/* Orders Table */}
          {loading ? (
            <div className="text-center py-12 text-sm text-gray-500 font-medium">
              Loading approved orders...
            </div>
          ) : orders.length === 0 ? (
            <div className="bg-white p-12 text-center rounded-2xl border border-gray-200 text-sm text-gray-500">
              {t.emptyOrders}
            </div>
          ) : (
            <div className="bg-white rounded-2xl border border-gray-200 shadow-sm overflow-hidden">
              <div className="overflow-x-auto">
                <table className="min-w-full divide-y divide-gray-200 text-left text-xs">
                  <thead className="bg-gray-50 text-gray-500 uppercase tracking-wider font-bold">
                    <tr>
                      <th scope="col" className="px-4 py-3 w-10">
                        <span className="sr-only">Select</span>
                      </th>
                      <th scope="col" className="px-4 py-3">
                        {t.colOrderNumber}
                      </th>
                      <th scope="col" className="px-4 py-3">
                        {t.colDate}
                      </th>
                      <th scope="col" className="px-4 py-3">
                        {t.colRetailer}
                      </th>
                      <th scope="col" className="px-4 py-3">
                        {t.colCases}
                      </th>
                      <th scope="col" className="px-4 py-3">
                        {t.colGross}
                      </th>
                      <th scope="col" className="px-4 py-3">
                        {t.colNet}
                      </th>
                      <th scope="col" className="px-4 py-3">
                        {t.colExportStatus}
                      </th>
                    </tr>
                  </thead>
                  <tbody className="divide-y divide-gray-100 bg-white">
                    {orders.map((o) => {
                      const isSelected = selectedIds.includes(o.id);
                      return (
                        <tr
                          key={o.id}
                          className={`hover:bg-primary-50/40 transition-colors cursor-pointer ${
                            isSelected ? 'bg-primary-50/70 font-semibold' : ''
                          }`}
                          onClick={() => toggleSelectOrder(o.id)}
                        >
                          <td className="px-4 py-3" onClick={(e) => e.stopPropagation()}>
                            <input
                              type="checkbox"
                              checked={isSelected}
                              onChange={() => toggleSelectOrder(o.id)}
                              className="h-4 w-4 rounded border-gray-300 text-primary-600 focus:ring-primary-500 cursor-pointer"
                            />
                          </td>
                          <td className="px-4 py-3 font-mono font-bold text-gray-900">
                            <Link
                              to={`/desk/orders/${o.id}`}
                              className="hover:text-primary-600 hover:underline"
                              onClick={(e) => e.stopPropagation()}
                            >
                              {o.order_number}
                            </Link>
                          </td>
                          <td className="px-4 py-3 text-gray-600">
                            {new Date(o.created_at).toLocaleDateString('en-IN', {
                              day: '2-digit',
                              month: 'short',
                              year: 'numeric',
                            })}
                          </td>
                          <td className="px-4 py-3">
                            <div className="font-bold text-gray-900">{o.retailer_name}</div>
                            <div className="text-[11px] text-gray-500 flex items-center gap-1">
                              <span>📱 {o.retailer_mobile}</span>
                              {o.tally_ledger_name && (
                                <span className="bg-indigo-50 text-indigo-700 px-1.5 py-0.2 rounded font-mono text-[10px]">
                                  Tally: {o.tally_ledger_name}
                                </span>
                              )}
                            </div>
                          </td>
                          <td className="px-4 py-3">
                            <span className="font-bold text-gray-900">{o.total_cases}</span>
                            <span className="text-gray-400"> / </span>
                            <span className="text-green-600 font-bold">+{o.total_free_cases}</span>
                            <span className="text-gray-400"> = </span>
                            <span className="font-black text-primary-700">
                              {o.total_fulfilment_cases}
                            </span>
                          </td>
                          <td className="px-4 py-3 text-gray-600 font-mono">
                            ₹{Number(o.gross_total).toFixed(2)}
                          </td>
                          <td className="px-4 py-3 font-black text-gray-900 font-mono">
                            ₹{Number(o.net_total).toFixed(2)}
                          </td>
                          <td className="px-4 py-3">
                            {o.export_count > 0 ? (
                              <span
                                className="inline-flex items-center gap-1 px-2 py-0.5 rounded-full text-[10px] font-bold bg-green-100 text-green-800"
                                title={`Last exported: ${
                                  o.last_exported_at
                                    ? new Date(o.last_exported_at).toLocaleString()
                                    : 'unknown'
                                }`}
                              >
                                <span>✓</span>
                                <span>
                                  {t.badgeExported} {o.export_count}x
                                </span>
                              </span>
                            ) : (
                              <span className="inline-flex items-center px-2 py-0.5 rounded-full text-[10px] font-semibold bg-gray-100 text-gray-600">
                                {t.badgeNotExported}
                              </span>
                            )}
                          </td>
                        </tr>
                      );
                    })}
                  </tbody>
                </table>
              </div>

              {/* Pagination */}
              {totalPages > 1 && (
                <div className="px-4 py-3 border-t border-gray-200 flex justify-between items-center text-xs">
                  <span className="text-gray-500">
                    Page {page} of {totalPages} ({totalOrders} orders)
                  </span>
                  <div className="flex gap-2">
                    <button
                      onClick={() => setPage((p) => Math.max(1, p - 1))}
                      disabled={page === 1}
                      className="px-3 py-1 bg-gray-100 hover:bg-gray-200 disabled:opacity-50 text-gray-700 rounded font-bold"
                    >
                      Previous
                    </button>
                    <button
                      onClick={() => setPage((p) => Math.min(totalPages, p + 1))}
                      disabled={page === totalPages}
                      className="px-3 py-1 bg-gray-100 hover:bg-gray-200 disabled:opacity-50 text-gray-700 rounded font-bold"
                    >
                      Next
                    </button>
                  </div>
                </div>
              )}
            </div>
          )}
        </div>
      )}

      {/* Tab 2: Export History */}
      {activeTab === 'history' && (
        <div className="bg-white rounded-2xl border border-gray-200 shadow-sm overflow-hidden">
          {batches.length === 0 ? (
            <div className="p-12 text-center text-sm text-gray-500">{t.emptyHistory}</div>
          ) : (
            <div className="overflow-x-auto">
              <table className="min-w-full divide-y divide-gray-200 text-left text-xs">
                <thead className="bg-gray-50 text-gray-500 uppercase tracking-wider font-bold">
                  <tr>
                    <th scope="col" className="px-4 py-3">
                      {t.colBatchNumber}
                    </th>
                    <th scope="col" className="px-4 py-3">
                      {t.colGeneratedAt}
                    </th>
                    <th scope="col" className="px-4 py-3">
                      {t.colOperator}
                    </th>
                    <th scope="col" className="px-4 py-3">
                      {t.colOrdersCount}
                    </th>
                    <th scope="col" className="px-4 py-3">
                      {t.colRecordsCount}
                    </th>
                    <th scope="col" className="px-4 py-3">
                      {t.casesSummary}
                    </th>
                    <th scope="col" className="px-4 py-3">
                      {t.colTotalNet}
                    </th>
                    <th scope="col" className="px-4 py-3 text-right">
                      {t.colAction}
                    </th>
                  </tr>
                </thead>
                <tbody className="divide-y divide-gray-100 bg-white">
                  {batches.map((b) => (
                    <tr key={b.id} className="hover:bg-gray-50 transition-colors">
                      <td className="px-4 py-3 font-mono font-bold text-gray-900">
                        {b.batch_number}
                        <div className="text-[10px] text-gray-400 font-mono">
                          {`SHA: ${b.file_checksum.slice(0, 10)}...`}
                        </div>
                      </td>
                      <td className="px-4 py-3 text-gray-600">
                        {new Date(b.generated_at).toLocaleString('en-IN', {
                          day: '2-digit',
                          month: 'short',
                          year: 'numeric',
                          hour: '2-digit',
                          minute: '2-digit',
                        })}
                      </td>
                      <td className="px-4 py-3 text-gray-700 font-medium">
                        {b.generator_name || 'Order Desk'}
                      </td>
                      <td className="px-4 py-3 font-bold text-gray-900">{b.order_count}</td>
                      <td className="px-4 py-3 text-gray-600">{b.record_count}</td>
                      <td className="px-4 py-3 font-black text-primary-700">
                        {b.total_fulfilment_cases}
                      </td>
                      <td className="px-4 py-3 font-mono font-black text-gray-900">
                        {`₹${Number(b.total_net).toFixed(2)}`}
                      </td>
                      <td className="px-4 py-3 text-right">
                        <button
                          onClick={() => handleDownloadExisting(b)}
                          disabled={downloadingId === b.id}
                          className="px-3 py-1.5 bg-gray-900 hover:bg-gray-800 disabled:bg-gray-400 text-white font-bold text-[11px] rounded-lg transition-colors inline-flex items-center gap-1"
                        >
                          <span>📥</span>
                          <span>{downloadingId === b.id ? t.downloading : t.downloadBtn}</span>
                        </button>
                      </td>
                    </tr>
                  ))}
                </tbody>
              </table>
            </div>
          )}
        </div>
      )}
    </div>
  );
};

export default DeskExportOrdersPage;
