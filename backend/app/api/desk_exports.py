"""
FastAPI router for Order Desk CSV Export & Accounting Integration (Phase 8).

Endpoints:
- GET /api/v1/desk/exports/profiles: List available export profiles (e.g. Generic Accounting)
- GET /api/v1/desk/exports/orders: Paginated list of exportable APPROVED orders
- POST /api/v1/desk/exports: Generate CSV export batch from selected approved orders
- GET /api/v1/desk/exports: Paginated list of historical export batches
- GET /api/v1/desk/exports/{batch_id}: Detail of a specific export batch
- GET /api/v1/desk/exports/{batch_id}/download: Stream/download the generated CSV file
"""

import uuid
from datetime import date
from typing import Optional, List
from fastapi import APIRouter, Depends, Query, Response, status
from sqlalchemy.orm import Session

from app.core.database import get_db
from app.api.deps import require_role
from app.services.export_service import ExportService, AVAILABLE_PROFILES
from app.schemas.export import (
    ExportProfileRead,
    ExportableOrderListResponse,
    CreateExportBatchRequest,
    ExportBatchRead,
    ExportBatchListResponse,
)

router = APIRouter(prefix="/desk/exports", tags=["desk-exports"])


@router.get(
    "/profiles",
    response_model=List[ExportProfileRead],
    summary="List available export profiles and caveats",
)
def get_export_profiles(
    current_user: dict = Depends(require_role(["order_desk"])),
):
    """
    Returns available export profiles (currently generic accounting format).
    Explicitly indicates that Tally Prime specific layouts are unconfirmed.
    """
    profiles = []
    for p in AVAILABLE_PROFILES.values():
        profiles.append(
            ExportProfileRead(
                key=p.key,
                display_name=p.display_name,
                description=p.description,
                is_preliminary=p.is_preliminary,
            )
        )
    return profiles


@router.get(
    "/orders",
    response_model=ExportableOrderListResponse,
    summary="List approved orders eligible for export",
)
def list_exportable_orders(
    page: int = Query(1, ge=1, description="Page number"),
    page_size: int = Query(20, ge=1, le=100, description="Page size"),
    search: Optional[str] = Query(None, description="Search order number or retailer name/mobile"),
    date_from: Optional[date] = Query(None, description="Start date filter (YYYY-MM-DD)"),
    date_to: Optional[date] = Query(None, description="End date filter (YYYY-MM-DD)"),
    current_user: dict = Depends(require_role(["order_desk"])),
    db: Session = Depends(get_db),
):
    """
    Returns exportable orders with pagination and filters.
    Strictly filters to orders with status APPROVED.
    """
    return ExportService.list_exportable_orders(
        db=db,
        page=page,
        page_size=page_size,
        search=search,
        date_from=date_from,
        date_to=date_to,
    )


@router.post(
    "",
    response_model=ExportBatchRead,
    status_code=status.HTTP_201_CREATED,
    summary="Generate an export batch for selected approved orders",
)
def create_export_batch(
    request: CreateExportBatchRequest,
    current_user: dict = Depends(require_role(["order_desk"])),
    db: Session = Depends(get_db),
):
    """
    Creates an export batch containing the requested approved orders.
    Enforces that all selected orders are in APPROVED status.
    Generates CSV, stores checksum and content, and creates audit records.
    """
    desk_user_id = uuid.UUID(current_user["id"])
    batch = ExportService.create_export_batch(
        db=db,
        desk_user_id=desk_user_id,
        order_ids=request.order_ids,
        profile_key=request.profile,
    )
    return batch


@router.get(
    "",
    response_model=ExportBatchListResponse,
    summary="List past export batches",
)
def list_export_batches(
    page: int = Query(1, ge=1, description="Page number"),
    page_size: int = Query(20, ge=1, le=100, description="Page size"),
    current_user: dict = Depends(require_role(["order_desk"])),
    db: Session = Depends(get_db),
):
    """
    Returns paginated list of historical export batches generated by Order Desk operators.
    """
    return ExportService.list_export_batches(
        db=db,
        page=page,
        page_size=page_size,
    )


@router.get(
    "/{batch_id}",
    response_model=ExportBatchRead,
    summary="Get detail and order references for an export batch",
)
def get_export_batch_detail(
    batch_id: uuid.UUID,
    current_user: dict = Depends(require_role(["order_desk"])),
    db: Session = Depends(get_db),
):
    """
    Returns details for a specific export batch including included order references.
    """
    return ExportService.get_export_batch(db=db, batch_id=batch_id)


@router.get(
    "/{batch_id}/download",
    summary="Download the CSV file for an export batch",
)
def download_export_batch_csv(
    batch_id: uuid.UUID,
    current_user: dict = Depends(require_role(["order_desk"])),
    db: Session = Depends(get_db),
):
    """
    Streams the stored CSV file for an export batch with proper Content-Disposition header.
    Content contains UTF-8 BOM so Excel opens Hindi/English text cleanly.
    """
    batch = ExportService.get_export_batch(db=db, batch_id=batch_id)

    # Encode with UTF-8
    content_bytes = batch.csv_content.encode("utf-8")

    return Response(
        content=content_bytes,
        media_type="text/csv; charset=utf-8",
        headers={
            "Content-Disposition": f'attachment; filename="{batch.csv_filename}"',
            "X-Checksum-SHA256": batch.file_checksum,
        },
    )

