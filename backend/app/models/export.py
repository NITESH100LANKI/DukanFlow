"""
SQLAlchemy ORM models for Tally-Compatible CSV Export & Accounting Integration (Phase 8):
- ExportBatch: Record of an export operation generated by an Order Desk user
- ExportBatchLine: Linkage between an ExportBatch and the exported Order snapshots
"""

import uuid
from datetime import datetime
from decimal import Decimal
from sqlalchemy import (
    String,
    Text,
    Integer,
    Numeric,
    DateTime,
    ForeignKey,
    Index,
    func,
)
from sqlalchemy.orm import Mapped, mapped_column, relationship
from sqlalchemy.types import Uuid
from app.core.database import Base


class ExportBatch(Base):
    """
    Record of an export batch generated by an Order Desk user.
    Maintains complete audit history and immutable stored CSV output.
    """
    __tablename__ = "export_batches"
    __table_args__ = (
        Index("ix_export_batches_generated_at_desc", "generated_at"),
    )

    id: Mapped[uuid.UUID] = mapped_column(
        Uuid(as_uuid=True), primary_key=True, default=uuid.uuid4
    )
    batch_number: Mapped[str] = mapped_column(
        String(50), unique=True, index=True, nullable=False
    )
    export_profile: Mapped[str] = mapped_column(
        String(50), default="generic", nullable=False
    )
    generated_by: Mapped[uuid.UUID] = mapped_column(
        Uuid(as_uuid=True),
        ForeignKey("order_desk_users.id", ondelete="RESTRICT"),
        nullable=False,
        index=True,
    )
    generated_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        server_default=func.now(),
        nullable=False,
    )
    order_count: Mapped[int] = mapped_column(Integer, default=0, nullable=False)
    record_count: Mapped[int] = mapped_column(Integer, default=0, nullable=False)

    total_gross: Mapped[Decimal] = mapped_column(
        Numeric(12, 2), default=Decimal("0.00"), nullable=False
    )
    total_discount: Mapped[Decimal] = mapped_column(
        Numeric(12, 2), default=Decimal("0.00"), nullable=False
    )
    total_benefit: Mapped[Decimal] = mapped_column(
        Numeric(12, 2), default=Decimal("0.00"), nullable=False
    )
    total_net: Mapped[Decimal] = mapped_column(
        Numeric(12, 2), default=Decimal("0.00"), nullable=False
    )
    total_fulfilment_cases: Mapped[int] = mapped_column(Integer, default=0, nullable=False)

    csv_filename: Mapped[str] = mapped_column(String(200), nullable=False)
    csv_content: Mapped[str] = mapped_column(Text, nullable=False)
    file_checksum: Mapped[str] = mapped_column(String(64), nullable=False)

    # Relationships
    generator: Mapped["app.models.auth.OrderDeskUser"] = relationship("OrderDeskUser")
    batch_lines: Mapped[list["ExportBatchLine"]] = relationship(
        "ExportBatchLine",
        back_populates="batch",
        cascade="all, delete-orphan",
        order_by="ExportBatchLine.created_at.asc()",
    )


class ExportBatchLine(Base):
    """
    Junction record capturing each Order included in an ExportBatch.
    Preserves audit linkage between orders and historical export batches.
    """
    __tablename__ = "export_batch_lines"
    __table_args__ = (
        Index("ix_export_batch_lines_batch_order", "batch_id", "order_id"),
        Index("ix_export_batch_lines_order_id", "order_id"),
    )

    id: Mapped[uuid.UUID] = mapped_column(
        Uuid(as_uuid=True), primary_key=True, default=uuid.uuid4
    )
    batch_id: Mapped[uuid.UUID] = mapped_column(
        Uuid(as_uuid=True),
        ForeignKey("export_batches.id", ondelete="CASCADE"),
        nullable=False,
        index=True,
    )
    order_id: Mapped[uuid.UUID] = mapped_column(
        Uuid(as_uuid=True),
        ForeignKey("orders.id", ondelete="RESTRICT"),
        nullable=False,
        index=True,
    )
    order_number_snapshot: Mapped[str] = mapped_column(
        String(50), nullable=False
    )
    order_net_total: Mapped[Decimal] = mapped_column(
        Numeric(12, 2), nullable=False
    )
    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        server_default=func.now(),
        nullable=False,
    )

    # Relationships
    batch: Mapped["ExportBatch"] = relationship("ExportBatch", back_populates="batch_lines")
    order: Mapped["app.models.order.Order"] = relationship("Order")

